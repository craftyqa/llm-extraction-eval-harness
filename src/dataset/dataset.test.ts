import { readFileSync } from "node:fs";
import { extname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { CASES } from "../../data/generator/cases.ts";
import { generatorOptionsSchema } from "../../data/generator/generate.ts";
import { FIELD_KINDS, FIELD_NAMES, type FieldName } from "../extract/fields.ts";
import { collapseWhitespace, groundEvidence } from "../extract/grounding.ts";
import { formatCents, normalise, toCents } from "../extract/normalise.ts";
import { ingest } from "../ingest/ingest.ts";
import { listCases } from "./cases.ts";
import { checkRules, type FoundValues, RULE_IDS } from "./rules.ts";
import { expectedSchema, metaSchema } from "./schema.ts";

/**
 * Dataset consistency tests (docs/specs.md, Phase 2; decision #41) over
 * `spec/examples/` and `data/cases/`. Model-free: they check the golden files
 * against SPEC.md and the app's own ingest, normalisers and grounding.
 */

const cases = listCases();
const riskIds = new Set(
  readFileSync(join(import.meta.dirname, "../../spec/risks.md"), "utf8")
    .match(/^\| R-\d+ /gmu)
    ?.map((s) => s.slice(2, -1)),
);
const generatorSpecs = new Map(CASES.map((c) => [c.info.id, c]));

it("finds the examples and the generated cases", () => {
  expect(
    cases.filter((c) => c.name.startsWith("spec/examples/")).length,
  ).toBeGreaterThanOrEqual(7);
  expect(
    cases.filter((c) => c.name.startsWith("data/cases/")).length,
  ).toBeGreaterThanOrEqual(CASES.length);
});

it("case ids are unique", () => {
  const ids = cases.map((c) => metaSchema.parse(c.meta).id);
  expect(ids.length - new Set(ids).size).toBe(0);
});

it("spec/risks.md lists R-1 to R-14", () => {
  expect([...riskIds]).toEqual(
    Array.from({ length: 14 }, (_, i) => `R-${String(i + 1)}`),
  );
});

describe.each(cases.map((c) => [c.name, c] as const))("%s", (_name, files) => {
  const expected = expectedSchema.safeParse(files.expected);
  const meta = metaSchema.safeParse(files.meta);

  it("expected.json and meta.json match their schemas", () => {
    expect(expected.error?.issues ?? []).toEqual([]);
    expect(meta.error?.issues ?? []).toEqual([]);
  });

  // The remaining tests need both files to parse; the test above reports why not.
  if (!expected.success || !meta.success) return;
  const e = expected.data;
  const m = meta.data;

  it("ids, source format and risks agree", () => {
    expect(e.caseId).toBe(m.id);
    const extension = extname(files.inputPath).slice(1).toLowerCase();
    expect(extension).toBe(m.sourceFormat);
    for (const risk of m.risks) expect(riskIds, risk).toContain(risk);
  });

  it("generator provenance matches data/generator/cases.ts", () => {
    const spec = generatorSpecs.get(m.id);
    if (m.generator !== undefined) {
      expect(
        generatorOptionsSchema.safeParse(m.generator.options).error?.issues ??
          [],
      ).toEqual([]);
    }
    if (spec !== undefined) {
      // Listed cases are regenerated byte for byte by data/generator/cases.test.ts
      expect(m.generator).toMatchObject({
        seed: spec.seed,
        options: spec.options,
      });
      expect(
        m.generator?.edited,
        "a hand-edited case must leave cases.ts",
      ).toBeUndefined();
    } else if (m.generator !== undefined) {
      // Not listed: only a hand-edited case may keep its generator block (decision #59)
      expect(
        m.generator.edited,
        "an unedited generated case must be listed in cases.ts",
      ).toBeDefined();
    }
  });

  if (e.status === "rejected") {
    it("lists no violated rules", () => {
      expect(m.violatesRules).toEqual([]);
    });
    return;
  }

  const found = Object.fromEntries(
    FIELD_NAMES.flatMap((name) => {
      const field = e.fields[name];
      return field.status === "found" ? [[name, field.value]] : [];
    }),
  ) as FoundValues;

  it("no decoy equals the field's value or an alternative", () => {
    for (const name of FIELD_NAMES) {
      const field = e.fields[name];
      if (field.status !== "found") continue;
      for (const correct of [field.value, ...(field.alternatives ?? [])]) {
        expect(field.decoys ?? [], `${name}: ${correct}`).not.toContain(
          correct,
        );
      }
    }
  });

  it("FMT-* rules hold", () => {
    const outcomes = checkRules(found);
    for (const id of RULE_IDS.filter((r) => r.startsWith("FMT-"))) {
      expect(outcomes[id], id).not.toBe("fail");
    }
  });

  it("XF-* rules hold unless listed in violatesRules, and listed rules fail", () => {
    const outcomes = checkRules(found);
    for (const id of RULE_IDS.filter((r) => r.startsWith("XF-"))) {
      expect(outcomes[id], id).toBe(
        m.violatesRules.includes(id)
          ? "fail"
          : outcomes[id] === "skipped"
            ? "skipped"
            : "pass",
      );
    }
    for (const id of m.violatesRules) {
      expect(
        id.startsWith("XF-"),
        `${id} can't be violated by the source; FMT-* rules hold on expected values`,
      ).toBe(true);
    }
  });

  it("every evidence quote grounds, and every raw normalises to the value", async () => {
    const ingested = await ingest(files.inputPath);
    expect(ingested.status).toBe("ok");
    if (ingested.status !== "ok") return;
    const source = ingested.source.text;
    const collapsed = collapseWhitespace(source);

    for (const name of FIELD_NAMES) {
      const field = e.fields[name];
      if (field.status !== "found" || field.evidence === undefined) continue;
      for (const { raw, quote } of field.evidence) {
        // SPEC §5 grounding
        expect(
          groundEvidence(raw, quote, collapsed).grounded,
          `${name}: ${raw} / ${quote}`,
        ).toBe(true);
      }
      expect(normalisedValue(name, field.evidence, source), name).toBe(
        isName(name) ? undefined : field.value,
      );
    }
  });
});

const isName = (name: FieldName) => FIELD_KINDS[name] === "name";

/**
 * What the app's normalisers make of the evidence (SPEC §4): the sum for
 * `taxAmount`, else the one value every raw agrees on. Names are stored as
 * printed and the expected value is canonical, so they aren't compared.
 */
function normalisedValue(
  name: FieldName,
  evidence: { raw: string }[],
  source: string,
): string | undefined {
  if (isName(name)) return undefined;
  const values = evidence.map(({ raw }) => {
    const result = normalise(FIELD_KINDS[name], raw, source);
    return result.ok ? result.value : `<${result.reason}: ${raw}>`;
  });
  if (name === "taxAmount") {
    if (values.some((v) => v.startsWith("<"))) return values.join(", ");
    return formatCents(values.reduce((sum, v) => sum + toCents(v), 0n));
  }
  const distinct = [...new Set(values)];
  return distinct.length === 1 ? distinct[0] : distinct.join(" ≠ ");
}
