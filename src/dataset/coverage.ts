import { PARTITIONS } from "./schema.ts";

/** A row of the `spec/risks.md` table. */
export type Risk = { id: string; severity: string; title: string };

/** The `meta.json` keys coverage reads. */
export type CaseMeta = {
  id: string;
  partition: string;
  risks: string[];
  smoke: boolean;
  reviewedBy: string | null;
};

/** Case counts per partition from the docs/specs.md Phase 2 target distribution (40 cases). */
export const PARTITION_TARGETS: Record<string, number> = {
  clean: 8,
  "missing fields": 6,
  "conflicting values": 4,
  decoys: 5,
  "messy formatting": 5,
  "boundary (cross-field)": 5,
  "should-reject": 7,
};

/** Phase 2 "done when": every risk has ≥ 1 case, every partition ≥ 3. */
export const MIN_CASES_PER_RISK = 1;
export const MIN_CASES_PER_PARTITION = 3;

export type Coverage = {
  cases: number;
  reviewed: number;
  smoke: number;
  risks: (Risk & { cases: string[]; smoke: string[]; examples: string[] })[];
  partitions: {
    name: string;
    target: number | null;
    cases: string[];
    smoke: string[];
    reviewed: number;
  }[];
  /** Risk × partition case counts. */
  matrix: Record<string, Record<string, number>>;
  /** Why the check fails; empty when it passes. */
  failures: string[];
};

/** Parses the risk table in `spec/risks.md`: `| R-1 | Risk text … | Fields | S1 | Caught by |`. */
export function parseRisks(markdown: string): Risk[] {
  const risks: Risk[] = [];
  for (const line of markdown.split("\n")) {
    const cells = line.split("|").map((c) => c.trim());
    const [, id = "", text = "", , severity = ""] = cells;
    // The coverage table at the bottom of risks.md has no severity column
    if (!/^R-\d+$/u.test(id) || !/^S[1-3]$/u.test(severity)) continue;
    // The risk itself, without its examples and consequence
    const title = (text.split(/ \(| →/u)[0] ?? text).trim();
    risks.push({ id, severity, title });
  }
  return risks;
}

/**
 * Coverage of risks and partitions by the dataset cases. `examples` (the
 * `spec/examples/` dev set) are listed per risk for reference but never count:
 * the prompts were tuned on them.
 */
export function computeCoverage(
  cases: readonly CaseMeta[],
  risks: readonly Risk[],
  examples: readonly CaseMeta[] = [],
): Coverage {
  const ids = (list: readonly CaseMeta[]) => list.map((c) => c.id);
  const partitionNames = PARTITIONS.filter(
    (p) => p in PARTITION_TARGETS || cases.some((c) => c.partition === p),
  );

  const riskRows = risks.map((risk) => {
    const tagged = cases.filter((c) => c.risks.includes(risk.id));
    return {
      ...risk,
      cases: ids(tagged),
      smoke: ids(tagged.filter((c) => c.smoke)),
      examples: ids(examples.filter((c) => c.risks.includes(risk.id))),
    };
  });

  const partitions = partitionNames.map((name) => {
    const inPartition = cases.filter((c) => c.partition === name);
    return {
      name,
      target: PARTITION_TARGETS[name] ?? null,
      cases: ids(inPartition),
      smoke: ids(inPartition.filter((c) => c.smoke)),
      reviewed: inPartition.filter((c) => c.reviewedBy !== null).length,
    };
  });

  const matrix: Coverage["matrix"] = {};
  for (const risk of risks) {
    matrix[risk.id] = Object.fromEntries(
      partitionNames.map((p) => [
        p,
        cases.filter((c) => c.partition === p && c.risks.includes(risk.id))
          .length,
      ]),
    );
  }

  const failures: string[] = [];
  for (const r of riskRows) {
    if (r.cases.length < MIN_CASES_PER_RISK)
      failures.push(`${r.id} (${r.severity}) has no case`);
  }
  for (const p of partitions) {
    if (p.target !== null && p.cases.length < MIN_CASES_PER_PARTITION) {
      failures.push(
        `partition "${p.name}" has ${String(p.cases.length)} of at least ${String(MIN_CASES_PER_PARTITION)} cases`,
      );
    }
  }

  return {
    cases: cases.length,
    reviewed: cases.filter((c) => c.reviewedBy !== null).length,
    smoke: cases.filter((c) => c.smoke).length,
    risks: riskRows,
    partitions,
    matrix,
    failures,
  };
}

/** `spec/coverage-matrix.md`. Deterministic (no timestamp), so it only changes when coverage does. */
export function renderCoverage(coverage: Coverage): string {
  const out: string[] = [];
  const list = (xs: readonly string[]) =>
    xs.length === 0 ? "—" : xs.join(", ");
  const count = (n: number, bold: boolean) =>
    bold ? `**${String(n)}**` : String(n);

  out.push(
    "# Coverage matrix",
    "",
    "Generated by `npm run coverage-matrix` from the `meta.json` tags in `data/cases/` and the risk list in [`risks.md`](risks.md). Don't edit by hand.",
    "",
    `**Status: ${coverage.failures.length === 0 ? "PASS" : "FAIL"}.** Every risk needs at least ${String(MIN_CASES_PER_RISK)} case and every partition at least ${String(MIN_CASES_PER_PARTITION)} (docs/specs.md, Phase 2). The \`spec/examples/\` dev set is listed for reference and doesn't count.`,
    "",
  );
  if (coverage.failures.length > 0) {
    out.push(...coverage.failures.map((f) => `- ${f}`), "");
  }
  out.push(
    `Cases: ${String(coverage.cases)} · reviewed: ${String(coverage.reviewed)} · smoke: ${String(coverage.smoke)}`,
    "",
    "## Risks",
    "",
    "| Risk | Sev | | Cases | Smoke | Dev examples |",
    "| --- | --- | --- | --- | --- | --- |",
  );
  for (const r of coverage.risks) {
    out.push(
      `| ${r.id} | ${r.severity} | ${r.title} | ${count(r.cases.length, r.cases.length < MIN_CASES_PER_RISK)}: ${list(r.cases)} | ${list(r.smoke)} | ${list(r.examples)} |`,
    );
  }

  out.push(
    "",
    "## Partitions",
    "",
    "| Partition | Cases | Target | Smoke | Reviewed |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const p of coverage.partitions) {
    const short = p.target !== null && p.cases.length < MIN_CASES_PER_PARTITION;
    out.push(
      `| ${p.name} | ${count(p.cases.length, short)} | ${p.target === null ? "—" : String(p.target)} | ${String(p.smoke.length)} | ${String(p.reviewed)} |`,
    );
  }

  const names = coverage.partitions.map((p) => p.name);
  out.push(
    "",
    "## Risk × partition",
    "",
    `| Risk | ${names.join(" | ")} |`,
    `| --- | ${names.map(() => "---").join(" | ")} |`,
  );
  for (const r of coverage.risks) {
    const row = coverage.matrix[r.id] ?? {};
    out.push(
      `| ${r.id} | ${names.map((n) => (row[n] ? String(row[n]) : "·")).join(" | ")} |`,
    );
  }
  return out.join("\n") + "\n";
}
